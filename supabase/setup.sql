    delivery_date = public.v_date(p, 'delivery_date', true, 'Delivery date'), delivery_time = public.v_str(p, 'delivery_time', false, 20),
    total_amount = tot, advance_paid = adv, status = st, notes = public.v_str(p, 'notes', false, 1000), updated_at = now()
  where id = p_id returning order_no into ono;
  if ono is null then raise exception 'Order not found'; end if;
  perform public.audit('order_updated', 'order', p_id::text, jsonb_build_object('order_no', ono));
  return jsonb_build_object('ok', true);
end $$;

create or replace function public.order_status(p_id bigint, p_status text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare o public.orders;
begin
  perform public.require_perm('orders.status', 'orders.manage');
  select * into o from public.orders where id = p_id;
  if o.id is null then raise exception 'Order not found'; end if;
  if not (p_status = any(array['pending','in_kitchen','ready','delivered','cancelled'])) then raise exception 'Status is invalid'; end if;
  if p_status = 'cancelled' and not public.has_perm('orders.manage') then
    raise exception 'Only order managers can cancel orders' using errcode = '42501';
  end if;
  update public.orders set status = p_status, updated_at = now() where id = p_id;
  perform public.audit('order_status', 'order', p_id::text, jsonb_build_object('order_no', o.order_no, 'from', o.status, 'to', p_status));
  return jsonb_build_object('ok', true);
end $$;

