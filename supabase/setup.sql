  from public.expenses where date between d_from and d_to
$$;

create or replace function public.dashboard() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare t date := public.app_today(); m_from date := date_trunc('month', t)::date; pm_from date; pm_same date;
  res jsonb; ms jsonb; me jsonb; ps jsonb; pe jsonb; pending jsonb; c public.daily_closings; y public.daily_closings; overdue jsonb := '[]';
  v record; b jsonb;
begin
  if (public.current_profile()).id is null then raise exception 'Please sign in.' using errcode = '28000'; end if;
  res := jsonb_build_object('today', t, 'month', to_char(t, 'YYYY-MM'));

  if public.has_perm('dashboard.financials') then
    pm_from := (m_from - interval '1 month')::date;
    pm_same := least(pm_from + (extract(day from t)::int - 1), (m_from - 1));
    ms := public.sales_between(m_from, t); me := public.expenses_between(m_from, t);
    ps := public.sales_between(pm_from, pm_same); pe := public.expenses_between(pm_from, pm_same);
    select * into c from public.daily_closings where date = t;
    select * into y from public.daily_closings where date = t - 1;
    select coalesce(jsonb_agg(x order by (x ->> 'pending')::numeric desc), '[]') into pending from (
      select jsonb_build_object('id', id, 'name', name, 'phone', phone, 'pending', public.vendor_pending(id)) x
      from public.vendors where active) z where (x ->> 'pending')::numeric > 0.009;
    for v in select id, name from public.vendors where active loop
      for b in select * from jsonb_array_elements(public.vendor_bills_status(v.id)) loop
        if (b ->> 'overdue')::boolean then
          overdue := overdue || jsonb_build_object('id', b -> 'id', 'bill_no', b -> 'bill_no', 'due_date', b -> 'due_date', 'amount', b -> 'amount',
            'balance', b -> 'balance', 'vendor_name', v.name, 'vendor_id', v.id);
        end if;
      end loop;
    end loop;
    res := res || jsonb_build_object('financials', jsonb_build_object(
      'today', jsonb_build_object('closing', case when c.id is null then null else public.closing_json(c) end, 'expenses', public.expenses_between(t, t)),
      'yesterday', case when y.id is null then null else public.closing_json(y) end,
      'month', jsonb_build_object('sales', ms, 'expenses', me, 'net', public.r2((ms ->> 'total')::numeric - (me ->> 'total')::numeric),
        'prev', jsonb_build_object('sales', ps, 'expenses', pe, 'net', public.r2((ps ->> 'total')::numeric - (pe ->> 'total')::numeric))),
      'series', (select jsonb_agg(jsonb_build_object('date', d::date,
          'cash', coalesce((select cash_sales from public.daily_closings where date = d::date), 0),
          'online', coalesce((select online_sales from public.daily_closings where date = d::date), 0),
          'expenses', coalesce((select sum(amount) from public.expenses where date = d::date), 0),
          'closed', exists (select 1 from public.daily_closings where date = d::date)) order by d)
        from generate_series(t - 29, t, interval '1 day') d),
      'expense_categories', coalesce((select jsonb_agg(x order by x.total desc) from (select category, sum(amount) total from public.expenses
        where date between m_from and t group by category) x), '[]'),
      'vendor_pending', jsonb_build_object('total', public.r2((select sum((x ->> 'pending')::numeric) from jsonb_array_elements(pending) x)),
        'count', jsonb_array_length(pending),
        'top', coalesce((select jsonb_agg(x) from (select x from jsonb_array_elements(pending) x limit 6) z), '[]')),
      'overdue_bills', coalesce((select jsonb_agg(x order by x ->> 'due_date') from (select x from jsonb_array_elements(overdue) x order by x ->> 'due_date' limit 6) z), '[]'),
      'recent_expenses', coalesce((select jsonb_agg(x) from (select e.id, e.date, e.category, e.amount, e.payment_mode, e.description, v2.name as vendor_name
        from public.expenses e left join public.vendors v2 on v2.id = e.vendor_id order by e.date desc, e.id desc limit 6) x), '[]')));
  end if;

  if public.has_perm('items.view') then
    res := res || jsonb_build_object('stock', jsonb_build_object(
      'low', coalesce((select jsonb_agg(x) from (select id, name, unit, stock_qty, reorder_level, type from public.items
        where active and reorder_level > 0 and stock_qty <= reorder_level order by stock_qty / reorder_level limit 8) x), '[]'),
      'counts', (select jsonb_build_object('total', count(*), 'products', count(*) filter (where type = 'product'),
        'low', count(*) filter (where reorder_level > 0 and stock_qty <= reorder_level)) from public.items where active)));
  end if;

  if public.has_perm('production.view') then
    res := res || jsonb_build_object('production', jsonb_build_object(
      'today', coalesce((select jsonb_agg(x order by x.made desc) from (select i.name as item_name, i.unit, sum(pl.qty_made) made,
        sum(coalesce(pl.qty_sold, 0)) sold, sum(pl.qty_wasted) wasted, count(*) filter (where pl.qty_sold is null) pending
        from public.production_logs pl join public.items i on i.id = pl.item_id where pl.date = t group by i.id) x), '[]'),
      'mine_today', (select jsonb_build_object('n', count(*), 'qty', coalesce(sum(qty_made), 0)) from public.production_logs where date = t and made_by = auth.uid())));
  end if;

  if public.has_perm('orders.view') then
    res := res || jsonb_build_object('orders', jsonb_build_object(
      'upcoming', coalesce((select jsonb_agg(x) from (select id, order_no, customer_name, item_desc, weight, delivery_date, delivery_time, status
        from public.orders where delivery_date between t and t + 7 and status not in ('delivered','cancelled')
        order by delivery_date, delivery_time limit 8) x), '[]'),
      'due_today', (select count(*) from public.orders where delivery_date = t and status not in ('delivered','cancelled')),
      'overdue', (select count(*) from public.orders where delivery_date < t and status not in ('delivered','cancelled'))));
  end if;

  if public.has_perm('closing.create', 'closing.manage') then
    res := res || jsonb_build_object('closing_status', jsonb_build_object('today_closed', exists (select 1 from public.daily_closings where date = t)));
  end if;
  return res;
end $$;

create or replace function public.report_monthly(p_month text default null) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare m text; d_from date; d_to date; days int; daily jsonb; sales jsonb; exps jsonb; closed int; best jsonb;
  pm_from date; pm_to date; ps jsonb; pe jsonb;
begin
  perform public.require_perm('reports.view');
  m := case when coalesce(p_month, '') ~ '^\d{4}-\d{2}$' then p_month else to_char(public.app_today(), 'YYYY-MM') end;
  d_from := public.month_start(m); d_to := (d_from + interval '1 month - 1 day')::date; days := extract(day from d_to)::int;
  select jsonb_agg(jsonb_build_object('date', d::date, 'closed', c.id is not null,
      'cash', coalesce(c.cash_sales, 0), 'online', coalesce(c.online_sales, 0), 'total', public.r2(coalesce(c.cash_sales + c.online_sales, 0)),
      'expenses', public.r2(e.total), 'net', public.r2(coalesce(c.cash_sales + c.online_sales, 0) - coalesce(e.total, 0))) order by d)
  into daily from generate_series(d_from, d_to, interval '1 day') d
    left join public.daily_closings c on c.date = d::date
    left join (select date, sum(amount) total from public.expenses where date between d_from and d_to group by date) e on e.date = d::date;
  sales := public.sales_between(d_from, d_to); exps := public.expenses_between(d_from, d_to);
  closed := (sales ->> 'days')::int;
  select x.value into best from jsonb_array_elements(daily) x where (x.value ->> 'closed')::boolean order by (x.value ->> 'total')::numeric desc limit 1;
  pm_from := (d_from - interval '1 month')::date; pm_to := d_from - 1;
  ps := public.sales_between(pm_from, pm_to); pe := public.expenses_between(pm_from, pm_to);
  return jsonb_build_object('month', m, 'from', d_from, 'to', d_to,
    'summary', jsonb_build_object('sales', sales, 'expenses', exps,
      'net', public.r2((sales ->> 'total')::numeric - (exps ->> 'total')::numeric),
      'avg_daily_sales', case when closed > 0 then public.r2((sales ->> 'total')::numeric / closed) else 0 end,
      'best_day', best, 'days_closed', closed, 'days_in_month', days,
      'online_share', case when (sales ->> 'total')::numeric > 0 then public.r2((sales ->> 'online')::numeric * 100 / (sales ->> 'total')::numeric) else 0 end,
      'prev', jsonb_build_object('month', to_char(pm_from, 'YYYY-MM'), 'sales', (ps ->> 'total')::numeric, 'expenses', (pe ->> 'total')::numeric,
        'net', public.r2((ps ->> 'total')::numeric - (pe ->> 'total')::numeric))),
    'daily', daily,
    'expense_categories', coalesce((select jsonb_agg(x order by x.total desc) from (select category, sum(amount) total, count(*) count
      from public.expenses where date between d_from and d_to group by category) x), '[]'),
    'expense_modes', coalesce((select jsonb_agg(x order by x.total desc) from (select payment_mode, sum(amount) total
      from public.expenses where date between d_from and d_to group by payment_mode) x), '[]'),
    'vendors', coalesce((select jsonb_agg(x order by x.billed desc, x.name) from (
      select v.id, v.name,
        coalesce((select sum(amount) from public.vendor_bills b where b.vendor_id = v.id and b.bill_date between d_from and d_to), 0) billed,
        coalesce((select sum(amount) from public.vendor_payments p where p.vendor_id = v.id and p.date between d_from and d_to), 0) paid,
        public.r2(v.opening_balance + coalesce((select sum(amount) from public.vendor_bills b where b.vendor_id = v.id and b.bill_date <= d_to), 0)
          - coalesce((select sum(amount) from public.vendor_payments p where p.vendor_id = v.id and p.date <= d_to), 0)) pending_at_month_end
      from public.vendors v) x where x.billed > 0 or x.paid > 0 or x.pending_at_month_end > 0.009), '[]'),
    'production', coalesce((select jsonb_agg(x order by x.sold desc) from (select i.id as item_id, i.name as item_name, i.unit, i.sell_price,
      sum(pl.qty_made) made, sum(coalesce(pl.qty_sold, 0)) sold, sum(pl.qty_wasted) wasted, count(distinct pl.date) days
      from public.production_logs pl join public.items i on i.id = pl.item_id where pl.date between d_from and d_to group by i.id) x), '[]'),
    'staff_production', coalesce((select jsonb_agg(x order by x.made desc) from (select u.name, u.role, count(*) entries, sum(pl.qty_made) made
      from public.production_logs pl join public.profiles u on u.id = pl.made_by where pl.date between d_from and d_to group by u.id) x), '[]'),
    'orders', (select jsonb_build_object('total', count(*), 'delivered', count(*) filter (where status = 'delivered'),
      'cancelled', count(*) filter (where status = 'cancelled'), 'value', coalesce(sum(total_amount) filter (where status <> 'cancelled'), 0))
      from public.orders where delivery_date between d_from and d_to));
end $$;

