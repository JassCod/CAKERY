create or replace function public.day_expenses(p_date date) returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'cash', public.r2(sum(amount) filter (where payment_mode = 'cash')),
    'online', public.r2(sum(amount) filter (where payment_mode <> 'cash')),
    'total', public.r2(sum(amount)), 'count', count(*))
  from public.expenses where date = p_date
$$;

create or replace function public.closing_json(c public.daily_closings) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare e jsonb := public.day_expenses(c.date); expected numeric;
begin
  expected := public.r2(c.opening_cash + c.cash_sales - (e ->> 'cash')::numeric);
  return to_jsonb(c) || jsonb_build_object(
    'closed_by_name', (select name from public.profiles where id = c.closed_by),
    'total_sales', public.r2(c.cash_sales + c.online_sales),
    'expenses_cash', (e ->> 'cash')::numeric, 'expenses_online', (e ->> 'online')::numeric, 'expenses_total', (e ->> 'total')::numeric,
    'expected_cash', expected,
    'cash_difference', case when c.cash_counted is null then null else public.r2(c.cash_counted - expected) end,
    'net', public.r2(c.cash_sales + c.online_sales - (e ->> 'total')::numeric));
end $$;

create or replace function public.closings_month(p_month text default null) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare m text := coalesce(nullif(p_month, ''), to_char(public.app_today(), 'YYYY-MM')); d_from date; d_to date; rows jsonb;
begin
  perform public.require_perm('closing.view');
  d_from := public.month_start(m); d_to := (d_from + interval '1 month - 1 day')::date;
  select coalesce(jsonb_agg(public.closing_json(c) order by c.date desc), '[]') into rows
    from public.daily_closings c where c.date between d_from and d_to;
  return jsonb_build_object('month', m, 'closings', rows,
    'totals', jsonb_build_object(
      'cash_sales', public.r2((select sum((r ->> 'cash_sales')::numeric) from jsonb_array_elements(rows) r)),
      'online_sales', public.r2((select sum((r ->> 'online_sales')::numeric) from jsonb_array_elements(rows) r)),
      'total_sales', public.r2((select sum((r ->> 'total_sales')::numeric) from jsonb_array_elements(rows) r)),
      'expenses_total', public.r2((select sum((r ->> 'expenses_total')::numeric) from jsonb_array_elements(rows) r)),
      'net', public.r2((select sum((r ->> 'net')::numeric) from jsonb_array_elements(rows) r))),
    'missing', coalesce((select jsonb_agg(d order by d desc) from (select distinct date d from public.expenses
      where date between d_from and d_to and date < public.app_today() and date not in (select date from public.daily_closings)) x), '[]'));
end $$;

create or replace function public.closing_day(p_date date) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare c public.daily_closings; prev public.daily_closings; prev_j jsonb; suggested numeric := 0;
begin
  perform public.require_perm('closing.view', 'closing.create');
  select * into c from public.daily_closings where date = p_date;
  select * into prev from public.daily_closings where date < p_date order by date desc limit 1;
  if prev.id is not null then
    prev_j := public.closing_json(prev);
    suggested := greatest(0, coalesce(prev.cash_counted, (prev_j ->> 'expected_cash')::numeric) - prev.cash_handover);
  end if;
  return jsonb_build_object('date', p_date,
    'closing', case when c.id is null then null else public.closing_json(c) end,
    'expenses', coalesce((select jsonb_agg(jsonb_build_object('id', e.id, 'category', e.category, 'amount', e.amount, 'payment_mode', e.payment_mode,
        'description', e.description, 'paid_to', e.paid_to, 'vendor_name', v.name) order by e.id)
      from public.expenses e left join public.vendors v on v.id = e.vendor_id where e.date = p_date), '[]'),
    'expense_totals', public.day_expenses(p_date),
    'suggested_opening', public.r2(suggested),
    'editable', public.has_perm('closing.manage') or (public.has_perm('closing.create') and p_date between public.app_today() - 1 and public.app_today()));
end $$;

create or replace function public.closing_save(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare d date; ex public.daily_closings; new_id bigint;
  o numeric; cs numeric; os numeric; cc numeric; ho numeric; nt text;
begin
  perform public.require_perm('closing.create', 'closing.manage');
  d := coalesce(public.v_date(p, 'date'), public.app_today());
  if not public.has_perm('closing.manage') and (d > public.app_today() or d < public.app_today() - 1) then
    raise exception 'You can only close today or yesterday. Ask a manager for older dates.' using errcode = '42501';
  end if;
  if d > public.app_today() then raise exception 'Cannot close a future date'; end if;
  o := public.v_num(p, 'opening_cash', false, 0, 'Opening cash', 0);
  cs := public.v_num(p, 'cash_sales', true, 0, 'Cash sales');
  os := public.v_num(p, 'online_sales', true, 0, 'Online sales');
  cc := public.v_num(p, 'cash_counted', false, 0, 'Cash counted');
  ho := public.v_num(p, 'cash_handover', false, 0, 'Cash handed over', 0);
  nt := public.v_str(p, 'notes', false, 1000);
  select * into ex from public.daily_closings where date = d;
  if ex.id is not null then
    update public.daily_closings set opening_cash = o, cash_sales = cs, online_sales = os, cash_counted = cc, cash_handover = ho,
      notes = nt, closed_by = auth.uid(), updated_at = now() where id = ex.id;
    perform public.audit('closing_updated', 'closing', ex.id::text, jsonb_build_object('date', d,
