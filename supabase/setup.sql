create or replace function public.month_start(p_month text) returns date
language plpgsql immutable as $$
begin
  if p_month is null or p_month !~ '^\d{4}-\d{2}$' then raise exception 'Month must be YYYY-MM'; end if;
  return (p_month || '-01')::date;
end $$;

create or replace function public.r2(n numeric) returns numeric language sql immutable as $$ select round(coalesce(n, 0), 2) $$;

-- ---------------------------------------------------------------------
-- Input validation helpers (read a key from a jsonb payload)
-- ---------------------------------------------------------------------
create or replace function public.v_str(p jsonb, k text, req boolean default false, maxlen int default 500, lbl text default null) returns text
language plpgsql immutable as $$
declare v text := nullif(btrim(coalesce(p ->> k, '')), '');
begin
  if v is null and req then raise exception '% is required', coalesce(lbl, k); end if;
  if v is not null and length(v) > maxlen then raise exception '% is too long', coalesce(lbl, k); end if;
  return v;
end $$;

create or replace function public.v_num(p jsonb, k text, req boolean default false, minv numeric default null, lbl text default null, def numeric default null) returns numeric
language plpgsql immutable as $$
declare raw text := nullif(btrim(coalesce(p ->> k, '')), ''); n numeric;
begin
  if raw is null then
    if req then raise exception '% is required', coalesce(lbl, k); end if;
    return def;
  end if;
  begin n := raw::numeric; exception when others then raise exception '% must be a number', coalesce(lbl, k); end;
  if minv is not null and n < minv then raise exception '% must be at least %', coalesce(lbl, k), minv; end if;
  if abs(n) > 1e11 then raise exception '% is too large', coalesce(lbl, k); end if;
  return round(n, 3);
end $$;

create or replace function public.v_date(p jsonb, k text, req boolean default false, lbl text default null) returns date
language plpgsql immutable as $$
declare raw text := nullif(btrim(coalesce(p ->> k, '')), '');
begin
  if raw is null then
    if req then raise exception '% is required', coalesce(lbl, k); end if;
    return null;
  end if;
  if raw !~ '^\d{4}-\d{2}-\d{2}$' then raise exception '% must be a valid date', coalesce(lbl, k); end if;
  begin return raw::date; exception when others then raise exception '% must be a valid date', coalesce(lbl, k); end;
end $$;

create or replace function public.v_bool(p jsonb, k text, def boolean) returns boolean
language sql immutable as $$
  select case when p ? k and jsonb_typeof(p -> k) <> 'null' then (p ->> k) in ('true', '1', 't', 'on') else def end
$$;

create or replace function public.v_oneof(p jsonb, k text, opts text[], def text default null, lbl text default null) returns text
language plpgsql immutable as $$
declare v text := coalesce(nullif(p ->> k, ''), def);
begin
  if v is null or not (v = any(opts)) then raise exception '% is invalid', coalesce(lbl, k); end if;
  return v;
end $$;

create or replace function public.v_id(p jsonb, k text, req boolean default false, lbl text default null) returns bigint
language plpgsql immutable as $$
declare raw text := nullif(btrim(coalesce(p ->> k, '')), '');
begin
  if raw is null then
    if req then raise exception '% is required', coalesce(lbl, k); end if;
    return null;
  end if;
  if raw !~ '^\d+$' then raise exception '% is invalid', coalesce(lbl, k); end if;
  return raw::bigint;
end $$;

