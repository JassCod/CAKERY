create or replace function public.items_list(p jsonb default '{}') returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare show_cost boolean; res jsonb; summ jsonb; q text := nullif(p ->> 'q', '');
begin
  perform public.require_perm('items.view');
  show_cost := public.has_perm('items.manage', 'dashboard.financials');
  select coalesce(jsonb_agg(case when show_cost then to_jsonb(i) else to_jsonb(i) - 'cost_price' end order by i.type, i.category, i.name), '[]')
  into res from public.items i
  where (public.v_bool(p, 'include_inactive', false) or i.active)
    and (q is null or i.name ilike '%' || q || '%' or i.sku ilike '%' || q || '%')
    and (nullif(p ->> 'type', '') is null or i.type = p ->> 'type')
    and (nullif(p ->> 'category', '') is null or i.category = p ->> 'category')
    and (coalesce(p ->> 'low', '') <> '1' or (i.reorder_level > 0 and i.stock_qty <= i.reorder_level));
  select jsonb_build_object('total', count(*),
      'low', count(*) filter (where stock_qty <= reorder_level and reorder_level > 0),
      'stock_value', case when show_cost then public.r2(sum(stock_qty * cost_price)) end)
    into summ from public.items where active;
  return jsonb_build_object('items', res, 'summary', summ);
end $$;

create or replace function public.item_save(p_id bigint, p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare it public.items; ex public.items; opening numeric; new_id bigint;
begin
  perform public.require_perm('items.manage');
  it.name := public.v_str(p, 'name', true, 120, 'Name');
  it.sku := public.v_str(p, 'sku', false, 40);
  it.type := public.v_oneof(p, 'type', array['product','ingredient','packaging','other'], 'product', 'Type');
  it.category := public.v_str(p, 'category', false, 60);
  it.unit := coalesce(public.v_str(p, 'unit', false, 20), 'pcs');
  it.cost_price := public.v_num(p, 'cost_price', false, 0, 'Cost price', 0);
  it.sell_price := public.v_num(p, 'sell_price', false, 0, 'Selling price', 0);
  it.reorder_level := public.v_num(p, 'reorder_level', false, 0, 'Reorder level', 0);
  it.notes := public.v_str(p, 'notes', false, 1000);
  it.active := public.v_bool(p, 'active', true);
  if p_id is null then
    opening := public.v_num(p, 'stock_qty', false, 0, 'Opening stock', 0);
    insert into public.items (name, sku, type, category, unit, cost_price, sell_price, stock_qty, reorder_level, notes, active)
    values (it.name, it.sku, it.type, it.category, it.unit, it.cost_price, it.sell_price, opening, it.reorder_level, it.notes, it.active)
    returning id into new_id;
    if opening > 0 then
      insert into public.stock_movements (item_id, change, balance, reason, note, user_id) values (new_id, opening, opening, 'adjustment', 'Opening stock', auth.uid());
    end if;
    perform public.audit('item_created', 'item', new_id::text, jsonb_build_object('name', it.name));
    return jsonb_build_object('id', new_id);
  end if;
  select * into ex from public.items where id = p_id;
  if ex.id is null then raise exception 'Item not found'; end if;
  update public.items set name = it.name, sku = it.sku, type = it.type, category = it.category, unit = it.unit,
    cost_price = it.cost_price, sell_price = it.sell_price, reorder_level = it.reorder_level, notes = it.notes,
    active = it.active, updated_at = now() where id = p_id;
  perform public.audit('item_updated', 'item', p_id::text, jsonb_build_object('name', it.name,
    'sell_price', jsonb_build_array(ex.sell_price, it.sell_price), 'cost_price', jsonb_build_array(ex.cost_price, it.cost_price)));
  return jsonb_build_object('ok', true);
end $$;

