create or replace function public.setting(k text) returns jsonb
language sql stable security definer set search_path = public as $$
  select value from public.settings where key = k
$$;

create or replace function public.app_today() returns date
language plpgsql stable security definer set search_path = public as $$
declare tz text := coalesce(public.setting('timezone') #>> '{}', 'Asia/Kolkata');
begin
  return (now() at time zone tz)::date;
exception when others then
  return (now() at time zone 'UTC')::date;
end $$;

create or replace function public.current_profile() returns public.profiles
language sql stable security definer set search_path = public as $$
  select * from public.profiles where id = auth.uid() and active
$$;

create or replace function public.perms_for(p_role text) returns text[]
language sql stable security definer set search_path = public as $$
  select case when p_role = 'owner'
    then (select array_agg(key order by sort) from public.permission_catalog) || array['roles.manage']
    else coalesce((select array_agg(permission) from public.role_permissions where role = p_role and permission <> '_none'), '{}')
  end
$$;

-- True when the signed-in, active user's role grants ANY of the given permissions.
create or replace function public.has_perm(variadic p_perms text[]) returns boolean
language plpgsql stable security definer set search_path = public as $$
declare r text;
begin
  select role into r from public.profiles where id = auth.uid() and active;
  if r is null then return false; end if;
  if r = 'owner' then return true; end if;
  return exists (select 1 from public.role_permissions where role = r and permission = any(p_perms));
end $$;

create or replace function public.require_perm(variadic p_perms text[]) returns void
language plpgsql stable security definer set search_path = public as $$
begin
  if auth.uid() is null or (public.current_profile()).id is null then
    raise exception 'Please sign in.' using errcode = '28000';
  end if;
  if not public.has_perm(variadic p_perms) then
    raise exception 'You do not have access to this action.' using errcode = '42501';
  end if;
end $$;

