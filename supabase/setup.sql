create or replace function public.roles_list() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare my_rank int;
begin
  perform public.require_perm('users.manage', 'roles.manage');
  my_rank := public.rank_of((public.current_profile()).role);
  return jsonb_build_object(
    'roles', (select jsonb_agg(jsonb_build_object('key', r.key, 'label', r.label, 'rank', r.rank, 'color', r.color,
        'permissions', to_jsonb(public.perms_for(r.key)), 'manageable', r.rank < my_rank,
        'users', (select count(*) from public.profiles u where u.role = r.key and u.active)) order by r.sort) from public.roles r),
    'groups', (select jsonb_agg(jsonb_build_object('group', g.grp, 'items', g.items) order by g.s)
      from (select grp, min(sort) s, jsonb_agg(jsonb_build_array(key, label) order by sort) items from public.permission_catalog group by grp) g));
end $$;

create or replace function public.role_update(p_role text, p_permissions text[]) returns jsonb
language plpgsql security definer set search_path = public as $$
declare clean text[];
begin
  perform public.require_perm('roles.manage');
  if not exists (select 1 from public.roles where key = p_role) then raise exception 'Unknown role'; end if;
  if p_role = 'owner' then raise exception 'Owner always has full access'; end if;
  select coalesce(array_agg(distinct p), '{}') into clean from unnest(coalesce(p_permissions, '{}')) p
    where p in (select key from public.permission_catalog);
  delete from public.role_permissions where role = p_role;
  insert into public.role_permissions (role, permission) select p_role, unnest(clean);
  if cardinality(clean) = 0 then insert into public.role_permissions values (p_role, '_none'); end if;
  perform public.audit('role_permissions_updated', 'role', p_role, jsonb_build_object('permissions', clean));
  return jsonb_build_object('ok', true, 'permissions', clean);
end $$;

