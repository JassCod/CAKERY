    'pending', public.vendor_pending(v.id))
$$;

-- Bills with paid / balance. Payments tied to a bill count against it; "on account"
-- payments (and overpayments) settle the opening balance first, then the oldest bills.
create or replace function public.vendor_bills_status(p_vendor bigint) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare pool numeric; b record; paid numeric; take numeric; bal numeric; st text; res jsonb := '[]'; t date := public.app_today();
begin
  select coalesce(sum(amount), 0) into pool from public.vendor_payments where vendor_id = p_vendor and bill_id is null;
  select pool + coalesce(sum(greatest(0, dp - amount)), 0) into pool from (
    select b2.amount, coalesce((select sum(amount) from public.vendor_payments p where p.bill_id = b2.id), 0) dp
    from public.vendor_bills b2 where b2.vendor_id = p_vendor) z;
  pool := pool - greatest(0, (select opening_balance from public.vendors where id = p_vendor));
  for b in select b2.*, least(b2.amount, coalesce((select sum(amount) from public.vendor_payments p where p.bill_id = b2.id), 0)) as direct_paid,
      (select count(*) from public.documents d where d.bill_id = b2.id) as doc_count, u.name as created_by_name
    from public.vendor_bills b2 left join public.profiles u on u.id = b2.created_by
    where b2.vendor_id = p_vendor order by b2.bill_date, b2.id
  loop
    paid := b.direct_paid;
    if pool > 0 and paid < b.amount then take := least(pool, b.amount - paid); paid := paid + take; pool := pool - take; end if;
    paid := public.r2(paid); bal := public.r2(b.amount - paid);
    st := case when bal <= 0.009 then 'paid' when paid > 0 then 'partial' else 'unpaid' end;
    res := jsonb_build_object('id', b.id, 'vendor_id', b.vendor_id, 'bill_no', b.bill_no, 'bill_date', b.bill_date, 'due_date', b.due_date,
      'amount', b.amount, 'description', b.description, 'created_by', b.created_by, 'created_at', b.created_at,
      'doc_count', b.doc_count, 'created_by_name', b.created_by_name, 'paid', paid, 'balance', bal, 'status', st,
      'overdue', st <> 'paid' and b.due_date is not null and b.due_date < t) || res;  -- prepend => newest first
  end loop;
  return res;
end $$;

create or replace function public.vendors_list(p jsonb default '{}') returns jsonb
