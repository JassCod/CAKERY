  return jsonb_build_object('ok', true);
end $$;

create or replace function public.item_stock(p_id bigint, p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare it public.items; dir text; qty numeric; reason text; chg numeric; bal numeric;
begin
  perform public.require_perm('stock.adjust', 'items.manage');
  select * into it from public.items where id = p_id for update;
  if it.id is null then raise exception 'Item not found'; end if;
  dir := public.v_oneof(p, 'direction', array['in','out','set'], 'in');
  qty := public.v_num(p, 'qty', true, 0, 'Quantity');
  reason := public.v_oneof(p, 'reason', array['purchase','usage','wastage','adjustment','return','production'],
    case when dir = 'in' then 'purchase' else 'usage' end, 'Reason');
  chg := case dir when 'set' then qty - it.stock_qty when 'in' then qty else -qty end;
  if chg = 0 then raise exception 'Nothing to change'; end if;
  bal := it.stock_qty + chg;
  update public.items set stock_qty = bal, updated_at = now() where id = p_id;
  insert into public.stock_movements (item_id, change, balance, reason, note, user_id)
  values (p_id, chg, bal, case when dir = 'set' then 'adjustment' else reason end, public.v_str(p, 'note', false, 300), auth.uid());
  perform public.audit('stock_changed', 'item', p_id::text, jsonb_build_object('name', it.name, 'change', chg, 'balance', bal, 'reason', reason));
  return jsonb_build_object('ok', true, 'balance', bal);
end $$;

