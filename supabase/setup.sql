create or replace function public.production_sales(p_id bigint, p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare pl public.production_logs; sold numeric; wasted numeric;
begin
  perform public.require_perm('production.sales', 'production.log', 'production.manage');
  select * into pl from public.production_logs where id = p_id;
