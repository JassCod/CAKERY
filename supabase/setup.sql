create or replace function public.vendor_detail(p_id bigint) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare v public.vendors; vr jsonb; docs jsonb := '[]'; bills jsonb; pays jsonb; ledger jsonb; bal numeric;
begin
  perform public.require_perm('vendors.view', 'documents.view');
  select * into v from public.vendors where id = p_id;
  if v.id is null then raise exception 'Vendor not found'; end if;
  vr := public.vendor_row(v);
  if public.has_perm('documents.view') then
    select coalesce(jsonb_agg(x order by coalesce(x.doc_date, x.created_at::date) desc, x.id desc), '[]') into docs from (
      select d.*, u.name as uploaded_by_name, b.bill_no from public.documents d left join public.profiles u on u.id = d.uploaded_by
      left join public.vendor_bills b on b.id = d.bill_id where d.vendor_id = p_id) x;
  end if;
  if not public.has_perm('vendors.view') then
    return jsonb_build_object('vendor', jsonb_build_object('id', v.id, 'name', v.name, 'category', v.category),
      'documents', docs, 'bills', '[]'::jsonb, 'payments', '[]'::jsonb, 'ledger', '[]'::jsonb);
  end if;
  bills := public.vendor_bills_status(p_id);
  select coalesce(jsonb_agg(x order by x.date desc, x.id desc), '[]') into pays from (
    select p.*, b.bill_no, u.name as created_by_name from public.vendor_payments p left join public.vendor_bills b on b.id = p.bill_id
    left join public.profiles u on u.id = p.created_by where p.vendor_id = p_id) x;
  bal := v.opening_balance;
  ledger := jsonb_build_array(jsonb_build_object('date', null, 'type', 'opening', 'description', 'Opening balance', 'debit', 0, 'credit', 0, 'balance', public.r2(bal)));
  declare e record;
  begin
    for e in select * from (
        select bill_date as date, 0 as ord, 'bill' as type, bill_no as ref, description, amount as debit, 0::numeric as credit, id from public.vendor_bills where vendor_id = p_id
        union all
        select date, 1, 'payment', reference, payment_mode || coalesce(' — ' || note, ''), 0, amount, id from public.vendor_payments where vendor_id = p_id) z
      order by date, ord, id
    loop
      bal := bal + e.debit - e.credit;
      ledger := ledger || jsonb_build_object('date', e.date, 'type', e.type, 'ref', e.ref, 'description', e.description,
        'debit', e.debit, 'credit', e.credit, 'id', e.id, 'balance', public.r2(bal));
    end loop;
  end;
  return jsonb_build_object('vendor', vr, 'bills', bills, 'payments', pays, 'documents', docs, 'ledger', ledger);
end $$;

