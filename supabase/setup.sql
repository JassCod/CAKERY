create or replace function public.production_list(p jsonb default '{}') returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare d_from date; d_to date; mine boolean; logs jsonb; summ jsonb; fin boolean;
begin
  perform public.require_perm('production.view');
  d_from := coalesce(public.v_date(p, 'from'), public.v_date(p, 'date'), public.app_today());
  d_to := coalesce(public.v_date(p, 'to'), d_from);
  mine := coalesce(p ->> 'mine', '') = '1';
  fin := public.has_perm('dashboard.financials');
  select coalesce(jsonb_agg(case when fin then to_jsonb(x) else to_jsonb(x) - 'sell_price' end order by x.date desc, x.item_name, x.id), '[]') into logs from (
    select pl.*, i.name as item_name, i.unit, i.category, i.sell_price, mu.name as made_by_name, su.name as sold_updated_by_name
    from public.production_logs pl join public.items i on i.id = pl.item_id
    left join public.profiles mu on mu.id = pl.made_by left join public.profiles su on su.id = pl.sold_updated_by
    where pl.date between d_from and d_to and (not mine or pl.made_by = auth.uid())) x;
  select coalesce(jsonb_agg(case when fin then to_jsonb(s) else to_jsonb(s) - 'sell_price' end order by s.made desc), '[]') into summ from (
    select i.id as item_id, i.name as item_name, i.unit, i.sell_price, sum(pl.qty_made) as made, sum(coalesce(pl.qty_sold, 0)) as sold,
      sum(pl.qty_wasted) as wasted, count(*) filter (where pl.qty_sold is null) as pending_counts
    from public.production_logs pl join public.items i on i.id = pl.item_id
    where pl.date between d_from and d_to and (not mine or pl.made_by = auth.uid()) group by i.id) s;
  return jsonb_build_object('from', d_from, 'to', d_to, 'logs', logs, 'summary', summ);
end $$;

create or replace function public.production_can_edit_own(pl public.production_logs) returns boolean
language sql stable security definer set search_path = public as $$
  select public.has_perm('production.manage') or (pl.made_by = auth.uid() and pl.date >= public.app_today() - 1)
$$;

create or replace function public.production_create(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare d date; it public.items; sold numeric; new_id bigint;
begin
  perform public.require_perm('production.log', 'production.manage');
  d := coalesce(public.v_date(p, 'date'), public.app_today());
  if not public.has_perm('production.manage') and (d > public.app_today() or d < public.app_today() - 1) then
    raise exception 'You can only log production for today or yesterday' using errcode = '42501';
  end if;
  select * into it from public.items where id = public.v_id(p, 'item_id', true, 'Item') and active;
  if it.id is null then raise exception 'Item not found'; end if;
  sold := public.v_num(p, 'qty_sold', false, 0, 'Quantity sold');
  insert into public.production_logs (date, item_id, qty_made, qty_sold, qty_wasted, notes, made_by, sold_updated_by)
  values (d, it.id, public.v_num(p, 'qty_made', true, 0, 'Quantity made'), sold, public.v_num(p, 'qty_wasted', false, 0, 'Quantity wasted', 0),
    public.v_str(p, 'notes', false, 500), auth.uid(), case when sold is null then null else auth.uid() end)
  returning id into new_id;
  perform public.audit('production_logged', 'production', new_id::text, jsonb_build_object('item', it.name, 'date', d, 'qty_made', p ->> 'qty_made'));
  return jsonb_build_object('id', new_id);
end $$;

