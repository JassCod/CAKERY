-- Called after the browser uploaded files to Storage (bucket "documents").
create or replace function public.document_add(p_vendor bigint, p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare vn text; bid bigint; f jsonb; ids bigint[] := '{}'; new_id bigint; path text;
  dtype text; ttl text; ddate date;
begin
  perform public.require_perm('documents.upload');
  select name into vn from public.vendors where id = p_vendor;
  if vn is null then raise exception 'Vendor not found'; end if;
  bid := public.v_id(p, 'bill_id');
  if bid is not null and not exists (select 1 from public.vendor_bills where id = bid and vendor_id = p_vendor) then
    raise exception 'Bill not found for this vendor';
  end if;
  dtype := public.v_oneof(p, 'doc_type', array['invoice','receipt','quotation','contract','credit_note','other'], 'invoice', 'Document type');
  ttl := public.v_str(p, 'title', false, 150);
  ddate := coalesce(public.v_date(p, 'doc_date'), public.app_today());
  if jsonb_typeof(p -> 'files') <> 'array' or jsonb_array_length(p -> 'files') = 0 then raise exception 'Choose at least one file'; end if;
  for f in select * from jsonb_array_elements(p -> 'files') loop
    path := f ->> 'path';
    if path is null or path not like 'vendors/' || p_vendor || '-%/%' or path like '%..%' then raise exception 'Invalid file path'; end if;
    insert into public.documents (vendor_id, bill_id, title, doc_type, doc_date, original_name, storage_path, mime, size, uploaded_by)
    values (p_vendor, bid, coalesce(ttl, left(f ->> 'name', 150)), dtype, ddate, left(coalesce(f ->> 'name', 'file'), 200), path,
      left(f ->> 'mime', 100), nullif(f ->> 'size', '')::bigint, auth.uid()) returning id into new_id;
    ids := ids || new_id;
  end loop;
  perform public.audit('documents_uploaded', 'vendor', p_vendor::text, jsonb_build_object('vendor', vn, 'count', cardinality(ids)));
  return jsonb_build_object('ids', to_jsonb(ids));
end $$;

create or replace function public.document_delete(p_vendor bigint, p_doc bigint) returns jsonb
language plpgsql security definer set search_path = public as $$
