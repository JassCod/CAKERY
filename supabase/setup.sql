language sql stable security definer set search_path = public as $$
  select public.r2(v.opening_balance + coalesce((select sum(amount) from public.vendor_bills where vendor_id = v.id), 0)
    - coalesce((select sum(amount) from public.vendor_payments where vendor_id = v.id), 0))
  from public.vendors v where v.id = p_vendor
$$;

