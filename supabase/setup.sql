-- Lock every table: no direct access with the public keys.
do $$
declare t text;
begin
  foreach t in array array['roles','permission_catalog','role_permissions','profiles','settings','items','stock_movements',
    'production_logs','daily_closings','vendors','vendor_bills','expenses','vendor_payments','documents','orders','audit_logs']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
  end loop;
end $$;

