create or replace function public.order_save(p_id bigint, p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare tot numeric; adv numeric; prefix text; n int; ono text; new_id bigint; st text;
begin
  perform public.require_perm('orders.manage');
  tot := public.v_num(p, 'total_amount', false, 0, 'Total amount', 0);
  adv := public.v_num(p, 'advance_paid', false, 0, 'Advance paid', 0);
  if adv > tot and tot > 0 then raise exception 'Advance cannot exceed total amount'; end if;
  st := public.v_oneof(p, 'status', array['pending','in_kitchen','ready','delivered','cancelled'], 'pending', 'Status');
  if p_id is null then
    perform pg_advisory_xact_lock(4243);
    prefix := 'ORD-' || to_char(public.app_today(), 'YYMMDD') || '-';
    select coalesce(max(substr(order_no, length(prefix) + 1)::int), 0) + 1 into n from public.orders where order_no like prefix || '%';
    ono := prefix || lpad(n::text, 3, '0');
    insert into public.orders (order_no, customer_name, phone, item_desc, weight, flavour, message, delivery_date, delivery_time,
      total_amount, advance_paid, status, notes, created_by)
    values (ono, public.v_str(p, 'customer_name', true, 100, 'Customer name'), public.v_str(p, 'phone', false, 30),
      public.v_str(p, 'item_desc', true, 300, 'Cake / item'), public.v_str(p, 'weight', false, 40), public.v_str(p, 'flavour', false, 80),
      public.v_str(p, 'message', false, 200), public.v_date(p, 'delivery_date', true, 'Delivery date'), public.v_str(p, 'delivery_time', false, 20),
      tot, adv, st, public.v_str(p, 'notes', false, 1000), auth.uid()) returning id into new_id;
    perform public.audit('order_created', 'order', new_id::text, jsonb_build_object('order_no', ono, 'customer', p ->> 'customer_name'));
    return jsonb_build_object('id', new_id, 'order_no', ono);
  end if;
  update public.orders set customer_name = public.v_str(p, 'customer_name', true, 100, 'Customer name'), phone = public.v_str(p, 'phone', false, 30),
    item_desc = public.v_str(p, 'item_desc', true, 300, 'Cake / item'), weight = public.v_str(p, 'weight', false, 40),
