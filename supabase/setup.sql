-- =====================================================================
--  Cakery — Supabase database setup
--  Paste this whole file into Supabase → SQL Editor → New query → Run.
--  Safe to run again later (it only creates what is missing and updates
--  functions), so re-run it after pulling a new version of the app.
--
--  Security model: every table has Row Level Security switched on with
--  NO policies, so nothing can be read or written directly with the
--  public (anon) key. The app only talks to the database through the
--  functions below, and each function checks the signed-in user's role
--  permissions first.
-- =====================================================================

