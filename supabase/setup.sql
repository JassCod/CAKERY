  end if;
  if not public.has_perm('production.manage') and pl.date < public.app_today() - 1 then
    raise exception 'Only managers can change counts for older days' using errcode = '42501';
  end if;
  sold := public.v_num(p, 'qty_sold', true, 0, 'Quantity sold');
  wasted := public.v_num(p, 'qty_wasted', false, 0, 'Quantity wasted', 0);
  update public.production_logs set qty_sold = sold, qty_wasted = wasted, sold_updated_by = auth.uid(), updated_at = now() where id = p_id;
  perform public.audit('production_sales_updated', 'production', p_id::text, jsonb_build_object('qty_sold', sold, 'qty_wasted', wasted));
  return jsonb_build_object('ok', true);
end $$;

