-- First-run only: creates the owner account while no owner exists.
create or replace function public.setup_owner(p_username text, p_password text, p_name text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare uid uuid;
begin
  perform pg_advisory_xact_lock(4242);
  if exists (select 1 from public.profiles where role = 'owner') then
    raise exception 'Setup is already complete. Please sign in.';
  end if;
  if nullif(btrim(coalesce(p_name, '')), '') is null then raise exception 'Name is required'; end if;
  uid := public.create_login(p_username, p_password, btrim(p_name), 'owner', null, false);
  insert into public.audit_logs (user_id, action, entity, entity_id) values (uid, 'owner_setup', 'user', uid::text);
  return jsonb_build_object('ok', true, 'email', public.staff_email(p_username));
end $$;

create or replace function public.me() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare p public.profiles; perms text[];
begin
  p := public.current_profile();
  if p.id is null then raise exception 'Please sign in.' using errcode = '28000'; end if;
  perms := public.perms_for(p.role);
  return jsonb_build_object(
    'user', jsonb_build_object('id', p.id, 'name', p.name, 'username', p.username, 'role', p.role, 'phone', p.phone,
      'role_label', (select label from public.roles where key = p.role), 'must_change_password', p.must_change_password),
    'permissions', to_jsonb(perms),
    'access', coalesce((select jsonb_agg(jsonb_build_object('group', g.grp, 'items', g.items) order by g.s)
      from (select grp, min(sort) s, jsonb_agg(label order by sort) items from public.permission_catalog
            where key = any(perms) group by grp) g), '[]'),
    'settings', public.settings_json());
end $$;

create or replace function public.after_login() returns jsonb
language plpgsql security definer set search_path = public as $$
declare p public.profiles;
begin
  select * into p from public.profiles where id = auth.uid();
  if p.id is null then raise exception 'This login has no staff profile. Ask the owner to create your account.'; end if;
  if not p.active then raise exception 'This account is disabled. Contact the owner.'; end if;
  update public.profiles set last_login = now() where id = p.id;
  perform public.audit('login', 'user', p.id::text);
  return jsonb_build_object('ok', true);
end $$;

create or replace function public.change_password(p_current text, p_new text) returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare hash text;
begin
  if (public.current_profile()).id is null then raise exception 'Please sign in.' using errcode = '28000'; end if;
  if p_new is null or length(p_new) < 6 then raise exception 'New password must be at least 6 characters'; end if;
  select encrypted_password into hash from auth.users where id = auth.uid();
  if hash is null or crypt(coalesce(p_current, ''), hash) <> hash then raise exception 'Current password is incorrect'; end if;
  update auth.users set encrypted_password = crypt(p_new, gen_salt('bf')), updated_at = now() where id = auth.uid();
  update public.profiles set must_change_password = false where id = auth.uid();
  perform public.audit('password_changed', 'user', auth.uid()::text);
  return jsonb_build_object('ok', true);
end $$;

